from google import genai
from google.genai import types

import itertools
import threading

class GeminiLLM:
    """
    Robust Gemini client that cycles across multiple flash models
    (gemini-3.5-flash-lite, gemini-3-flash-preview, gemini-3.6-flash)
    to distribute calls across distinct quota pools and avoid 429 / 503 rate limits.
    """
    MODELS = ["gemini-3.5-flash-lite", "gemini-3-flash-preview", "gemini-3.6-flash"]

    def __init__(self):
        self.client = genai.Client(api_key=os.getenv("GOOGLE_API_KEY"))
        self._counter = itertools.count()
        self._lock = threading.Lock()

    def _get_next_model(self) -> str:
        with self._lock:
            idx = next(self._counter)
        return self.MODELS[idx % len(self.MODELS)]

    def _convert_messages(self, messages) -> str:
        text = ""
        for m in messages:
            content = getattr(m, "content", str(m))
            text += f"{content}\n\n"
        return text.strip()

    def invoke(self, messages):
        prompt = self._convert_messages(messages)
        start_model = self._get_next_model()
        model_list = [start_model] + [m for m in self.MODELS if m != start_model]

        last_err = None
        for model in model_list:
            try:
                resp = self.client.models.generate_content(
                    model=model,
                    contents=prompt
                )
                class Res:
                    content = (resp.text or "").strip()
                return Res()
            except Exception as e:
                last_err = e
                continue
        raise last_err or RuntimeError("All Gemini models failed.")

    def with_structured_output(self, schema):
        parent = self
        class StructuredInvoker:
            def invoke(self, messages):
                prompt = parent._convert_messages(messages)
                start_model = parent._get_next_model()
                model_list = [start_model] + [m for m in parent.MODELS if m != start_model]

                last_err = None
                for model in model_list:
                    try:
                        resp = parent.client.models.generate_content(
                            model=model,
                            contents=prompt,
                            config=types.GenerateContentConfig(
                                response_mime_type="application/json",
                                response_schema=schema
                            )
                        )
                        return schema.model_validate_json(resp.text)
                    except Exception as e:
                        last_err = e
                        continue
                raise last_err or RuntimeError("All Gemini structured models failed.")
        return StructuredInvoker()

